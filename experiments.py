"""
Experiments.

E1  Cross-bed transfer.  Train on two beds (coronary, carotid), test on the
    four others.  Three representations of the same information are compared:
        A   raw lesion + device features, bed as a one-hot category
        A'  raw lesion + device features, bed as continuous physiology
        B   the four numbers the suitcordance operator produces
    The claim under test is the pan-vascular one: that a device-vessel
    agreement operator transfers across beds where a categorical bed effect
    cannot.

E2  Sample efficiency within the coronary bed.

E3  Decision utility.  Simulated 12-month event rate under a fixed protocol,
    under the starting harness, under the evolved harness, and under the
    catalogue oracle.

WHAT THESE EXPERIMENTS DO NOT SHOW.  Outcomes here are generated by the same
operator that model B consumes, so E1 and E2 cannot prove that Gamma_sc is
true of patients.  What they can show is a property of the representation:
whether a physics-parameterised summary survives a distribution shift that a
categorical encoding does not, when both are fed the same information and both
see the features through realistic measurement noise and an unobserved frailty
term.  Whether that carries to real cohorts is what fit_real.py is for.
"""

from __future__ import annotations
import json
import os
import sys
from typing import Dict, List, Tuple

import numpy as np
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import roc_auc_score, brier_score_loss
from sklearn.preprocessing import StandardScaler

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from panvas.beds import BEDS, BED_KEYS
from panvas.devices import BY_KEY, PREP, candidates_for
from panvas.suitcordance import Lesion, Plan, evaluate
from panvas.tasks import sample

RNG = np.random.default_rng(20260918)
FRAILTY_SD = 0.55          # unobserved patient-level hazard multiplier, log scale


# --------------------------------------------------------------------------
# cohort
# --------------------------------------------------------------------------
def random_plan(les: Lesion, rng) -> Plan:
    """A deliberately varied plan, so the cohort spans good and bad matches."""
    pool = candidates_for(les.bed, les.d_ref)
    dev = pool[rng.integers(len(pool))]
    mult = float(rng.uniform(0.85, 1.45))
    lo, hi = dev.d_range
    nd = float(np.clip(round(les.d_ref * mult * 4) / 4, lo, hi))
    want = les.length + 2 * float(rng.uniform(-3.0, 8.0))
    n_dev = max(1, int(np.ceil(want / dev.l_max)))
    L = float(np.clip(want / n_dev, 8.0, dev.l_max))
    prep = ["none", "noncomp", "scoring", "atherec", "ivl"][rng.integers(5)]
    return Plan(device=dev.key, nominal_d=nd, length=L, prep=prep,
                postdilate=bool(rng.random() < 0.4), n_devices=n_dev)


def observe(les: Lesion, rng) -> Lesion:
    """What the operator actually measures, not what is true."""
    jitter = 0.16 if les.d_ref < 4 else 0.35          # mm, QCA / duplex error
    return Lesion(
        bed=les.bed,
        d_prox=float(max(1.0, les.d_prox + rng.normal(0, jitter))),
        d_dist=float(max(1.0, les.d_dist + rng.normal(0, jitter))),
        length=float(max(4.0, les.length * (1 + rng.normal(0, 0.12)))),
        stenosis=les.stenosis,
        calcium=float(np.clip(round(les.calcium * 3) / 3, 0, 1)),   # graded 0/1/2/3
        tortuosity=float(np.clip(round(les.tortuosity * 2) / 2, 0, 1)),
        bifurcation=les.bifurcation, side_branch=les.side_branch, cto=les.cto,
        diabetes=les.diabetes, inflammation=les.inflammation, runoff=les.runoff)


def build_cohort(n: int, seed: int) -> Tuple[List[dict], np.ndarray]:
    rng = np.random.default_rng(seed)
    lesions = sample(n, seed=seed)
    rows, y = [], []
    for les in lesions:
        plan = random_plan(les, rng)
        truth = evaluate(les, plan, horizon=380, dt=10.0)
        frailty = float(np.exp(rng.normal(0, FRAILTY_SD)))
        p = 1.0 - (1.0 - truth.risk_12m) ** frailty
        event = int(rng.random() < p)

        obs = observe(les, rng)
        seen = evaluate(obs, plan, horizon=380, dt=10.0)
        rows.append(dict(les=les, obs=obs, plan=plan, seen=seen))
        y.append(event)
    return rows, np.array(y)


# --------------------------------------------------------------------------
# representations
# --------------------------------------------------------------------------
FAMILIES = ["DES", "BRS", "BMS", "SE", "SE-DES", "COVERED", "DCB", "POBA"]
PREPS = list(PREP.keys())


def _raw_block(row: dict) -> List[float]:
    o, p = row["obs"], row["plan"]
    dev = BY_KEY[p.device]
    pot = {"none": 0.0, "paclitaxel": 1.0, "sirolimus": 1.25, "everolimus": 1.2}[dev.drug]
    f = [o.d_ref, o.taper, o.length, o.stenosis, o.calcium, o.tortuosity,
         float(o.bifurcation), float(o.side_branch), float(o.cto),
         float(o.diabetes), o.inflammation, float(o.runoff),
         p.nominal_d, p.length, float(p.n_devices), float(p.postdilate),
         p.nominal_d / o.d_ref, (p.length * p.n_devices - o.length) / 2.0,
         dev.strut_um, dev.radial_force, dev.conformability, dev.fatigue_resist,
         dev.dose_ug_mm2 * pot, dev.drug_tau_d,
         0.0 if dev.degrade_tau_d is None else dev.degrade_tau_d]
    f += [1.0 if dev.family == fam else 0.0 for fam in FAMILIES]
    f += [1.0 if p.prep == pr else 0.0 for pr in PREPS]
    return f


def feats_A(rows: List[dict]) -> np.ndarray:
    """Raw features, bed as a one-hot category."""
    out = []
    for r in rows:
        f = _raw_block(r)
        f += [1.0 if r["obs"].bed == b else 0.0 for b in BED_KEYS]
        out.append(f)
    return np.array(out, dtype=float)


def feats_Ap(rows: List[dict]) -> np.ndarray:
    """Raw features, bed as continuous physiology instead of a label."""
    out = []
    for r in rows:
        bed = BEDS[r["obs"].bed]
        f = _raw_block(r)
        f += [bed.compliance, bed.wss0, bed.k_neointima, bed.cyclic_strain,
              bed.tau_endo, np.log(bed.lambda0)]
        out.append(f)
    return np.array(out, dtype=float)


def feats_B(rows: List[dict]) -> np.ndarray:
    """What the suitcordance operator produces, computed from OBSERVED inputs."""
    out = []
    for r in rows:
        s = r["seen"]
        bed = BEDS[r["obs"].bed]
        out.append([float(np.mean(s.gamma[:37])), s.deficit,
                    s.tau_sc / 365.0, np.log(bed.lambda0)])
    return np.array(out, dtype=float)


# A and A' use a tree, which can only interpolate between values it has seen, so
# with a handful of training beds the continuous bed parameters behave exactly
# like a one-hot and the two arms coincide.  A'' is the same features under a
# linear model, which CAN extrapolate along them: it separates "the operator is
# a better representation" from "a linear model extrapolates and a tree does not".
REPRESENTATIONS = {
    "A   raw + bed one-hot (tree)": (feats_A, "gbm"),
    "A'  raw + bed physiology (tree)": (feats_Ap, "gbm"),
    "A'' raw + bed physiology (linear)": (feats_Ap, "lr"),
    "B   suitcordance, 4 numbers (linear)": (feats_B, "lr"),
}


def fit_predict(Xtr, ytr, Xte, kind: str):
    if kind == "gbm":
        m = HistGradientBoostingClassifier(max_iter=300, learning_rate=0.06,
                                           max_leaf_nodes=15, l2_regularization=1.0,
                                           random_state=0)
        m.fit(Xtr, ytr)
        return m.predict_proba(Xte)[:, 1]
    sc = StandardScaler().fit(Xtr)
    m = LogisticRegression(max_iter=2000, C=1.0)
    m.fit(sc.transform(Xtr), ytr)
    return m.predict_proba(sc.transform(Xte))[:, 1]


# --------------------------------------------------------------------------
TRAIN_BEDS = ("coronary", "carotid")            # two beds, so that bed physiology
TEST_BEDS = ("sfa", "btk", "renal", "iliac")    # is at least partly identifiable
                                                # for A'; with one training bed
                                                # every bed column is constant and
                                                # A and A' are the same model.


def _boot_auc_diff(y, p1, p2, n_boot=400, seed=3) -> Tuple[float, float]:
    rng = np.random.default_rng(seed)
    idx = np.arange(len(y))
    d = []
    for _ in range(n_boot):
        b = rng.choice(idx, len(idx), replace=True)
        if y[b].sum() in (0, len(b)):
            continue
        d.append(roc_auc_score(y[b], p1[b]) - roc_auc_score(y[b], p2[b]))
    return float(np.percentile(d, 2.5)), float(np.percentile(d, 97.5))


def e1_transfer(rows, y) -> Dict:
    beds = np.array([r["obs"].bed for r in rows])
    tr = np.isin(beds, TRAIN_BEDS)
    te = np.isin(beds, TEST_BEDS)
    print(f"\nE1  cross-bed transfer   train n={tr.sum()} {TRAIN_BEDS}  "
          f"test n={te.sum()} {TEST_BEDS}")
    print(f"    event rate  train {y[tr].mean():.3f}  test {y[te].mean():.3f}")
    print(f"    (base-rate-only Brier on the test beds: "
          f"{brier_score_loss(y[te], np.full(te.sum(), y[te].mean())):.4f})")
    print(f"    {'representation':36s} {'in-bed AUC':>11s} {'cross AUC':>10s} "
          f"{'cross Brier':>12s} {'recalibrated':>13s}")
    res, preds = {}, {}
    for name, (fn, kind) in REPRESENTATIONS.items():
        X = fn(rows)
        idx = np.where(tr)[0]
        half = len(idx) // 2
        p_in = fit_predict(X[idx[:half]], y[idx[:half]], X[idx[half:]], kind)
        auc_in = roc_auc_score(y[idx[half:]], p_in)
        p_out = np.clip(fit_predict(X[tr], y[tr], X[te], kind), 1e-6, 1 - 1e-6)
        preds[name] = p_out
        auc_out = roc_auc_score(y[te], p_out)
        br = brier_score_loss(y[te], p_out)
        # an intercept shift is what bed-level recalibration would buy; it uses
        # the test base rate, so read it as a ceiling, not an out-of-sample score
        lr = LogisticRegression(max_iter=1000)
        lr.fit(np.log(p_out / (1 - p_out)).reshape(-1, 1), y[te])
        br_rc = brier_score_loss(
            y[te], lr.predict_proba(np.log(p_out / (1 - p_out)).reshape(-1, 1))[:, 1])
        print(f"    {name:36s} {auc_in:11.3f} {auc_out:10.3f} {br:12.4f} {br_rc:13.4f}")
        res[name] = dict(auc_in=auc_in, auc_cross=auc_out, brier_cross=br,
                         brier_cross_recalibrated=br_rc)

    a_key = "A'' raw + bed physiology (linear)"
    b_key = "B   suitcordance, 4 numbers (linear)"
    lo, hi = _boot_auc_diff(y[te], preds[b_key], preds[a_key])
    print(f"    cross-bed AUC advantage of B over A'':  "
          f"{res[b_key]['auc_cross'] - res[a_key]['auc_cross']:+.3f} "
          f"(95% bootstrap {lo:+.3f} to {hi:+.3f})")
    res["auc_diff_ci"] = [lo, hi]
    return res


def e2_sample_efficiency(rows, y) -> Dict:
    beds = np.array([r["obs"].bed for r in rows])
    idx = np.where(beds == "coronary")[0]
    RNG.shuffle(idx)
    hold = idx[-400:]
    pool = idx[:-400]
    sizes = [100, 200, 400, 800, 1200]
    sizes = [s for s in sizes if s <= len(pool)]
    print(f"\nE2  sample efficiency, coronary only, held-out n={len(hold)}")
    print("    " + f"{'representation':36s}" + "".join(f"{s:>8d}" for s in sizes))
    res = {}
    for name, (fn, kind) in REPRESENTATIONS.items():
        X = fn(rows)
        aucs = []
        for s in sizes:
            p = fit_predict(X[pool[:s]], y[pool[:s]], X[hold], kind)
            aucs.append(roc_auc_score(y[hold], p))
        print("    " + f"{name:36s}" + "".join(f"{a:8.3f}" for a in aucs))
        res[name] = dict(sizes=sizes, auc=aucs)
    return res


def e3_decision_utility(n: int = 300) -> Dict:
    from panvas.agent import HARNESS_V0, propose, oracle
    import copy
    print(f"\nE3  decision utility, n={n} fresh cases across all beds")
    cases = sample(n, seed=4242)

    harness_final = None
    fp = "harness/harness_final.json"
    if os.path.exists(fp):
        harness_final = json.load(open(fp, encoding="utf-8"))

    def fixed_protocol(les: Lesion, _h=None) -> Plan:
        """Always the workhorse implant for the bed, sized 1:1, no preparation."""
        pool = candidates_for(les.bed, les.d_ref)
        pref = {"coronary": "des_thin", "sfa": "se_nitinol", "btk": "des_thin",
                "carotid": "car_closed", "renal": "bms", "iliac": "se_nitinol"}
        dev = BY_KEY.get(pref[les.bed], pool[0])
        band = BEDS[les.bed].oversize_band
        mid = 0.5 * (band[0] + band[1]) if dev.expansion == "self" else 1.0
        nd = float(np.clip(round(les.d_ref * mid * 4) / 4, *dev.d_range))
        n_dev = max(1, int(np.ceil((les.length + 6) / dev.l_max)))
        return Plan(device=dev.key, nominal_d=nd,
                    length=min(dev.l_max, (les.length + 6) / n_dev), n_devices=n_dev)

    strategies = {"fixed protocol": lambda l: fixed_protocol(l),
                  "harness v0": lambda l: propose(l, HARNESS_V0)}
    if harness_final:
        strategies["harness evolved"] = lambda l: propose(l, harness_final)
    strategies["catalogue oracle"] = lambda l: oracle(l)[1]

    res = {}
    for name, fn in strategies.items():
        risks = [evaluate(l, fn(l), horizon=380, dt=10.0).risk_12m for l in cases]
        res[name] = float(np.mean(risks))
        print(f"    {name:20s} mean predicted 12-month event rate {np.mean(risks):.4f}")
    return res


def main() -> None:
    print("building cohort ...")
    rows, y = build_cohort(9000, seed=11)
    print(f"  n={len(rows)}  overall 12-month event rate {y.mean():.3f}")

    out = dict(e1=e1_transfer(rows, y),
               e2=e2_sample_efficiency(rows, y),
               e3=e3_decision_utility())
    os.makedirs("out", exist_ok=True)
    with open("out/experiments.json", "w", encoding="utf-8") as fh:
        json.dump(out, fh, indent=2, default=float)
    print("\nwritten: out/experiments.json")


if __name__ == "__main__":
    main()
